//! Reviewed table of readable public semantic contracts.
//!
//! The types in this file are deliberately independent mirrors of public options
//! and observations. A case contains a sentence-case test name, pattern/input
//! bytes, options, one operation, and a directly readable expected value. It has
//! no opaque ID, feature category, intent prose, or answer generated from the
//! engine.
//!
//! `conformance_test.zig` validates structural compatibility and instantiates one
//! Zig test per row at comptime. The custom runner maps the generated index back
//! to the human name. Keeping data here free of execution helpers makes review of
//! the semantic corpus distinct from review of the harness.

pub const Span = struct { start: usize, end: usize };
pub const Operation = enum { compile, exists, find, captures, full_match, full_captures };
pub const Encoding = enum { utf8, latin1 };
pub const Semantics = enum { perl, posix };
pub const MatchKind = enum { first, longest };
pub const Anchor = enum { unanchored, start };
pub const Diagnostic = enum {
    bad_escape,
    bad_char_range,
    missing_bracket,
    missing_paren,
    unexpected_paren,
    trailing_backslash,
    repeat_argument,
    repeat_size,
    repeat_operator,
    bad_perl_operator,
    bad_utf8,
    bad_named_capture,
    resource_limit,
};

/// Independent subset of CompileOptions needed by handwritten contracts.
pub const Options = struct {
    encoding: Encoding = .utf8,
    semantics: Semantics = .perl,
    match_kind: MatchKind = .first,
    case_sensitive: bool = true,
    dot_matches_newline: bool = false,
    exclude_newline: bool = false,
    text_anchors: bool = false,
    literal: bool = false,
    capture_groups: bool = true,
    perl_classes: bool = false,
    word_boundary: bool = false,
    compile_memory: ?usize = null,
};

/// Expected whole range and up to three explicit capture-group ranges.
pub const MatchExpected = struct {
    whole: Span,
    captures: []const ?Span = &.{},
};

/// Readable observation shape corresponding to one `Operation`.
pub const Expected = union(enum) {
    compile_ok,
    compile_error: Diagnostic,
    no_match,
    exists,
    match: MatchExpected,
};

